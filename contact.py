"""Sampled point-contact feasibility, with a conservative polygonal Coulomb cone.
NNLS projects the required wrench onto the cone generated by nonnegative ray forces.
The same projection residual enters the unified differentiable trajectory objective.
"""
import numpy as np
import torch
from scipy.optimize import nnls, lsq_linear
import dynamics

RAYS = 8

def vector(value, name):
    a = np.asarray(value, dtype=float)
    if a.shape != (3,) or not np.isfinite(a).all():
        raise ValueError('invalid ' + name)
    return a

def rays(normal, mu):
    n = vector(normal, 'normal')
    if not np.isclose(np.linalg.norm(n), 1, atol=1e-8, rtol=0):
        raise ValueError('contact normal must be unit length')
    if not np.isfinite(mu) or mu < 0:
        raise ValueError('invalid friction coefficient')
    if mu == 0:
        return n[None]
    t = np.cross(n, np.eye(3)[np.argmin(abs(n))]); t /= np.linalg.norm(t)
    u = np.cross(n, t)
    a = np.arange(RAYS) * (2*np.pi/RAYS)
    return n + mu*(np.cos(a)[:,None]*t + np.sin(a)[:,None]*u)

def prepare(d, physical):
    """Absent schedule = unknown; explicit empty schedule = flight everywhere.
    Inclusive frame ranges; all uncovered frames in an explicit schedule are flight.
    """
    hints = d.get('solverHints', {})
    if 'physicalContacts' not in hints:
        return None
    if physical is None:
        raise ValueError('physicalContacts require body mass properties')
    t = d['timeline']; F = t['end']-t['start']+1; names = d['rig']['bones']
    if F < 3:
        raise ValueError('physicalContacts require at least three frames')
    raw = hints['physicalContacts']
    if not isinstance(raw, list):
        raise ValueError('physicalContacts must be a list')
    cfg = hints.get('contactOptions', {})
    def positive(k, default):
        v = float(cfg.get(k, default))
        if not np.isfinite(v) or v <= 0: raise ValueError('invalid '+k)
        return v
    opts = dict(length=positive('momentLengthM', 1.), force_tol=positive('forceToleranceN', 1.), torque_tol=positive('momentToleranceNm', 1.), gap_tol=positive('anchorToleranceM', .005), weight=positive('objectiveWeightM2', .02), anchor_weight=positive('anchorWeight', 2.))
    items=[]; used=set()
    for c in raw:
        if not isinstance(c.get('id'), str) or not c['id'] or c['id'] in used: raise ValueError('unique contact id required')
        used.add(c['id']); j=names.index(c['bone']); lo=c['start']; hi=c['end']
        if type(lo)!=int or type(hi)!=int or not t['start']<=lo<=hi<=t['end']: raise ValueError('invalid contact range')
        n=vector(c['normal'],'normal'); mu=float(c['mu']); D=rays(n,mu)
        items.append(dict(id=c['id'], j=j, lo=lo-t['start'], hi=hi-t['start'], local=vector(c['localPointM'],'localPointM'), anchor=vector(c['anchorM'],'anchorM'), normal=n, mu=mu, rays=D))
    active=[[i for i,c in enumerate(items) if c['lo']<=k<=c['hi']] for k in range(F)]
    return dict(items=items, active=active, opts=opts, start=t['start'])

def project(A, target):
    """Nonnegative least squares in scaled wrench space; check KKT on the result."""
    if A.shape[1]==0: return np.zeros(0)
    # scipy's active-set implementation can struggle with redundant rays.
    try: x=nnls(A,target,maxiter=max(100,20*A.shape[1]))[0]
    except (RuntimeError, np.linalg.LinAlgError):
        sol=lsq_linear(A,target,bounds=(0,np.inf),method='bvls',tol=1e-12,max_iter=max(100,20*A.shape[1]))
        if not sol.success: raise RuntimeError('contact projection did not converge')
        x=sol.x
    grad=A.T@(A@x-target)
    tol=1e-7*max(1.,np.linalg.norm(A,ord=2)*np.linalg.norm(target))
    if not np.isfinite(x).all() or x.min() < -1e-10 or grad.min() < -tol or np.max(abs(grad[x>1e-8]),initial=0)>tol:
        raise RuntimeError('contact projection failed KKT check')
    return np.maximum(x,0)

def evaluate(G,P,params,parents,fps,schedule,details=False):
    """Compute required external wrench about root and its feasible point-force projection.
    NNLS coefficients are detached: envelope theorem gives the derivative of the
    minimized squared residual w.r.t. A and target (a.e., at converged projection).
    """
    m,c,I,g=params; q=dynamics.evaluate(G,P,m,c,I,parents,fps,g)
    opts=schedule['opts']; ell=opts['length']; items=schedule['items']; active=schedule['active']
    T=lambda v: torch.as_tensor(v,dtype=P.dtype,device=P.device)
    points=[P[:,a['j']]+(G[:,a['j']]@T(a['local'])[:,None]).squeeze(-1) for a in items]
    gaps=[points[i][a['lo']:a['hi']+1]-T(a['anchor']) for i,a in enumerate(items)]
    anchor_loss=torch.cat(gaps).square().sum(-1).mean() if gaps else P.sum()*0
    residual=[]; records=[]
    for k in range(1,len(P)-1):
        target=torch.cat((q['joint_force'][k-1,0],q['joint_torque'][k-1,0]/ell))
        cols=[]
        for i in active[k]:
            D=T(items[i]['rays']); arm=(points[i][k]-P[k,0]).expand_as(D)
            cols.append(torch.cat((D,torch.linalg.cross(arm,D)/ell),dim=-1).T)
        A=torch.cat(cols,dim=1) if cols else P.new_zeros((6,0))
        x=T(project(A.detach().cpu().numpy(),target.detach().cpu().numpy()))
        delta=target-A@x; residual.append(delta)
        if details:
            forces=[]; pos=0
            for i in active[k]:
                a=items[i]; D=T(a['rays']); f=x[pos:pos+len(D)]@D; pos+=len(D)
                forces.append(dict(id=a['id'],point_m=points[i][k].tolist(),force_N=f.tolist(),normal_N=float(f@T(a['normal'])),tangent_N=float(torch.linalg.vector_norm(f-(f@T(a['normal']))*T(a['normal']))),mu=a['mu']))
            records.append(dict(frame=schedule['start']+k,mode='CONTACT' if cols else 'FLIGHT',required_force_N=target[:3].tolist(),required_moment_Nm=(target[3:]*ell).tolist(),residual_force_N=delta[:3].tolist(),residual_moment_Nm=(delta[3:]*ell).tolist(),forces=forces))
    res=torch.stack(residual)
    # Normalize by characteristic weight; zero gravity uses 1 m/s², not divide by zero.
    scale=m.sum()*torch.linalg.vector_norm(g).clamp_min(1.)
    loss=opts['weight']*(res/scale).square().sum(-1).mean()+opts['anchor_weight']*anchor_loss
    if not details:return loss
    fmax=float(torch.linalg.vector_norm(res[:,:3],dim=-1).max()); tmax=float(torch.linalg.vector_norm(res[:,3:]*ell,dim=-1).max()); gapmax=max((float(torch.linalg.vector_norm(x,dim=-1).max()) for x in gaps),default=0.)
    flags=[]
    if fmax>opts['force_tol'] or tmax>opts['torque_tol']:flags.append('CONTACT_WRENCH_RESIDUAL')
    if gapmax>opts['gap_tol']:flags.append('CONTACT_ANCHOR_DRIFT')
    return dict(status='REVIEW_REQUIRED' if flags else 'SAMPLED_CONTACT_FEASIBLE',flags=flags,force_residual_max_N=fmax,moment_residual_max_Nm=tmax,anchor_gap_max_m=gapmax,settings=opts,friction_cone='inscribed 8-ray cone (conservative)',frames=records,endpoint_wrench_status='NOT_EVALUATED',limitations='Prescribed sticking point contacts; no free moment, impact, sliding, inactive geometry or actuator limits. Feasible for sampled net wrench only.')

def report(G,P,params,parents,fps,schedule):
    with torch.no_grad():
        return evaluate(torch.as_tensor(G,dtype=torch.float64),torch.as_tensor(P,dtype=torch.float64),params,parents,fps,schedule,details=True)
